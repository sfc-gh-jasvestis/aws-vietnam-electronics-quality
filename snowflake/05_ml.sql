-- Hold-risk scoring and first-pass yield forecast over the synthetic snapshot.
-- Predicts P(quality hold in the next 7 days) per line and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.HOLD_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.CTQ_DEV_PCT, r.BOARD_TEMP_C,
       AVG(r.CTQ_DEV_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS CTQ_DEV_7D,
       SUM(r.HOLD_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS HOLDS_30D,
       IFF(SUM(r.HOLD_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'HOLD', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.LINE_DAILY r JOIN RAW.LINES t ON t.ID = r.ENTITY_ID
-- Utility power dips are not line-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE <> 'Utility power dip' OR r.HOLD_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.HOLD_TRAIN AS
SELECT CATEGORY, AGE_YEARS, CTQ_DEV_PCT, BOARD_TEMP_C, CTQ_DEV_7D, HOLDS_30D, LABEL
FROM ML.HOLD_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.HOLD_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, CTQ_DEV_PCT, BOARD_TEMP_C, CTQ_DEV_7D, HOLDS_30D, LABEL
FROM ML.HOLD_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.HOLD_RISK_MODEL(
  INPUT_DATA => TABLE(ML.HOLD_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.HOLD_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.HOLD_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'CTQ_DEV_PCT', CTQ_DEV_PCT,
           'BOARD_TEMP_C', BOARD_TEMP_C, 'CTQ_DEV_7D', CTQ_DEV_7D, 'HOLDS_30D', HOLDS_30D)):probability:HOLD::FLOAT AS P
  FROM ML.HOLD_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'HOLD', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'HOLD', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'HOLD', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'HOLD', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per line (label unknown, so excluded from features).
CREATE TABLE ML.HOLD_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.HOLD_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.HOLD_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'CTQ_DEV_PCT', CTQ_DEV_PCT,
           'BOARD_TEMP_C', BOARD_TEMP_C, 'CTQ_DEV_7D', CTQ_DEV_7D, 'HOLDS_30D', HOLDS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:HOLD::FLOAT, 4) AS HOLD_PROB_7D,
       CASE WHEN P:probability:HOLD::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:HOLD::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide first-pass yield forecast (14 days) from the daily series.
CREATE VIEW ML.DAILY_YIELD AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, 100.0 * SUM(BOARDS_PASSED) / SUM(BOARDS_STARTED) AS FIRST_PASS_YIELD_PCT
FROM RAW.LINE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.YIELD_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_YIELD),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'FIRST_PASS_YIELD_PCT'
);

CREATE TABLE ML.YIELD_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, LEAST(100, FORECAST) AS FIRST_PASS_YIELD_PCT,
       LOWER_BOUND, LEAST(100, UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.YIELD_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
